function mergeUniqueExtensions(
  ...groups: readonly (readonly string[])[]
): readonly string[] {
  return [...new Set(groups.flat())]
}

export const VLC_MEDIA_EXTENSIONS = mergeUniqueExtensions(
  VLC_AUDIO_EXTENSIONS,
  VLC_VIDEO_EXTENSIONS,
)

export type MediaFileType = 'audio' | 'video' | 'subtitles' | 'media'

export const MEDIA_FILE_EXTENSIONS: Record<MediaFileType, readonly string[]> = {
  audio: VLC_AUDIO_EXTENSIONS,
  video: VLC_VIDEO_EXTENSIONS,
  subtitles: VLC_SUBTITLE_EXTENSIONS,
  media: VLC_MEDIA_EXTENSIONS,
}
